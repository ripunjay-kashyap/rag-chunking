"""Run-to-run stability of generated answers: the same prompts, generated twice.

Temperature 0 does not make a hosted LLM deterministic. Comparing two independent
generations measures how much of an answer-accuracy difference is noise.
Both generations are labelled with the same automatic check, so the comparison doesn't
depend on any hand-made label.
"""

from __future__ import annotations

import json
from pathlib import Path

from rag_chunking.evaluation.answer_key import AnswerKey
from rag_chunking.evaluation.autocheck import SCORES, check_answer


def _answers(run_dir: Path) -> dict[str, dict] | None:
    path = run_dir / "answers.json"
    if not path.is_file():
        return None
    return {a["id"]: a for a in json.loads(path.read_text(encoding="utf-8"))["answers"]}


def compare(key: AnswerKey, first: Path, second: Path, run_ids: list[str]) -> str:
    lines = [
        "# Answer stability: two generations of the same prompts",
        "",
        f"_Generated by `python -m rag_chunking stability --other {second}`._",
        "",
        f"First generation: `{first}/<run>/answers.json` (the committed results). Second "
        f"generation: `{second}/<run>/answers.json`, produced by a cold-cache `run --all` "
        "from a fresh clone. The prompts are identical: the retrieved contexts matched "
        "chunk for chunk and score for score. Both are labelled with the automatic check "
        "against the frozen answer key.",
        "",
        "| Run | Answer acc. (1st) | Answer acc. (2nd) | Δ | Answer texts changed "
        "| Label changes (1st → 2nd) |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for run_id in run_ids:
        a, b = _answers(first / run_id), _answers(second / run_id)
        if a is None or b is None:
            continue
        for qid in a:
            if a[qid]["context_ids"] != b[qid]["context_ids"]:
                raise ValueError(f"{run_id} {qid}: contexts differ, so prompts differ")
        labels = {
            q.id: tuple(check_answer(q, gen[q.id]["answer"]).label for gen in (a, b))
            for q in key.questions
        }
        acc = [
            round(100 * sum(SCORES[pair[i]] for pair in labels.values()) / len(labels), 1)
            for i in (0, 1)
        ]
        changed = sum(a[q]["answer"].strip() != b[q]["answer"].strip() for q in a)
        flips = ", ".join(f"{q}: {x} → {y}" for q, (x, y) in labels.items() if x != y) or "none"
        lines.append(
            f"| `{run_id}` | {acc[0]}% | {acc[1]}% | {acc[1] - acc[0]:+.1f} "
            f"| {changed}/{len(a)} | {flips} |"
        )
    return "\n".join(lines) + "\n"
